from ..core.context import ToolError

INLINE_TAGS = ("h1", "h2", "h3", "h4", "h5", "h6", "p", "a", "span", "li", "blockquote", "button", "small", "strong")
URL_RE = re.compile(r"^/[\w\-/.~%]*$")


def website(ctx, website_id=None):
    env = ctx.env
    if "website" not in env:
        raise ToolError("The Website app is not installed in this database.")
    Website = env["website"].sudo()
    if website_id:
        w = Website.browse(int(website_id)).exists()
        if not w:
            raise ToolError("Website %s does not exist." % website_id)
        return w
    perms = env["nxb.mcp.site.permission"].sudo().search([("active", "=", True)])
    if len(perms) == 1:
        return perms._website()
    ws = Website.search([], limit=2)
    if len(ws) == 1:
        return ws
    raise ToolError("Several websites exist; pass website_id (see site_overview).")


def permission(ctx, w, flag=None):
    perm = ctx.env["nxb.mcp.site.permission"].sudo().search([("website_key", "=", str(w.id)), ("active", "=", True)],
                                                             limit=1)
    if not perm:
        raise ToolError("The assistant is not allowed to change website %r yet. An administrator must add it in "
                        "AI Connector → AI workspace → Website permissions and choose what is allowed." % w.name)
    if flag and not perm[flag]:
        label = perm._fields[flag].string
        raise ToolError("'%s' is not allowed for website %r. An administrator can enable it in Website "
                        "permissions." % (label, w.name))
    return perm


def find_page(ctx, w, page):
    """Find a page by URL or id, preferring the website-specific version."""
    Page = ctx.env["website.page"].sudo().with_context(website_id=w.id)
    if isinstance(page, int) or (isinstance(page, str) and page.isdigit()):
        p = Page.browse(int(page)).exists()
    else:
        url = (page or "/").strip()
        if url.startswith("http"):
            url = "/" + url.split("/", 3)[3] if url.count("/") >= 3 else "/"
        url = url.split("?")[0].split("#")[0]
        if not url.startswith("/"):
            url = "/" + url
        url = url.rstrip("/") or "/"
        p = Page.search([("url", "=", url), ("website_id", "=", w.id)], limit=1) or \
            Page.search([("url", "=", url), ("website_id", "=", False)], limit=1)
        if not p and url == "/":
            home = w.homepage_url or "/"
            if home != "/":
                return find_page(ctx, w, home)
            p = Page.search([("view_id.key", "=", "website.homepage"), ("website_id", "in", (w.id, False))],
                            order="website_id", limit=1)
    if not p:
        raise ToolError("No page %r on website %r. Use site_pages to list pages." % (page, w.name))
    if p.website_id and p.website_id != w:
        raise ToolError("Page %r belongs to another website." % page)
    return p


def own_page(ctx, w, page):
    """Return a page specific to website ``w`` (copy-on-write of a shared page if needed)."""
    if not page.website_id:
        view = page.view_id.with_context(website_id=w.id)
        view.write({"arch": view.arch})  # triggers Odoo's copy-on-write
        page = find_page(ctx, w, page.url)
    return page


def check_page(ctx, perm, page):
    if not perm._page_allowed(page.url):
        raise ToolError("Page %s is not in the list of pages the assistant may change. An administrator can add it "
                        "in Website permissions." % page.url)


def read_arch(view):
    try:
        return etree.fromstring(view.arch_db or view.arch)
    except etree.XMLSyntaxError as e:
        raise ToolError("This page cannot be edited automatically (its template is not valid XML: %s)." % e)


def wrap_of(root):
    wrap = root.xpath("//div[@id='wrap']")
    if not wrap:
        raise ToolError("This page has no editable content area (it is probably generated by an app, not a "
                        "regular page).")
    return wrap[0]


def sections(wrap):
    return [c for c in wrap if isinstance(c.tag, str)]


def get_section(wrap, index):
    secs = sections(wrap)
    try:
        index = int(index)
    except (TypeError, ValueError):
        raise ToolError("'section' must be a number (see the page structure).")
    if index < 1 or index > len(secs):
        raise ToolError("Section %s does not exist; the page has %d sections (numbered from 1)." % (index, len(secs)))
    return secs[index - 1]


def rel_path(section, el):
    tree = section.getroottree()
    base = tree.getpath(section)
    return tree.getpath(el)[len(base):] or "."


def get_element(section, path):
    if not path or path == ".":
        return section
    if not path.startswith("/") or ".." in path or "(" in path:
        raise ToolError("Element paths come from the page structure, e.g. /div/div[1]/h1.")
    found = section.xpath("." + path)
    if not found:
        raise ToolError("Element %s was not found in this section. Read the page structure again." % path)
    return found[0]


def text_of(el, limit=140):
    t = " ".join((el.xpath("string(.)") or "").split())
    return t[:limit] + ("…" if len(t) > limit else "")


def outline(wrap, detail=True):
    out = []
    for i, sec in enumerate(sections(wrap), start=1):
        classes = (sec.get("class") or "").split()
        item = {"section": i, "block": sec.get("data-snippet") or next((c for c in classes if c.startswith("s_")),
                                                                         sec.tag),
                "name": sec.get("data-name") or "", "classes": " ".join(classes)[:160],
                "summary": text_of(sec, 160)}
        if detail:
            elems = []
            for el in sec.iter():
                if not isinstance(el.tag, str):
                    continue
                if el.tag in ("h1", "h2", "h3", "h4", "h5", "h6"):
                    elems.append({"path": rel_path(sec, el), "type": el.tag, "text": text_of(el)})
                elif el.tag == "p" and len(elems) < 40:
                    elems.append({"path": rel_path(sec, el), "type": "p", "text": text_of(el, 100)})
                elif el.tag == "a" and ("btn" in (el.get("class") or "") or el.get("href")):
                    elems.append({"path": rel_path(sec, el), "type": "button" if "btn" in (el.get("class") or "")
                                  else "link", "text": text_of(el, 60), "href": el.get("href") or ""})
                elif el.tag == "img":
                    elems.append({"path": rel_path(sec, el), "type": "image", "src": (el.get("src") or "")[:200],
                                  "alt": el.get("alt") or ""})
            item["elements"] = elems[:60]
        out.append(item)
    return out


def snapshot(ctx, w, page, label):
    view = page.view_id
    snap = ctx.env["nxb.mcp.site.snapshot"].sudo().create({
        "website_id_int": w.id, "view_id_int": view.id, "page_url": page.url, "label": label,
        "arch": view.arch_db or view.arch})
    return snap


def save_arch(ctx, w, page, root, label):
    """Snapshot the current version, then save the new arch."""
    snap = snapshot(ctx, w, page, label)
    page.view_id.with_context(website_id=w.id).write({"arch": etree.tostring(root, encoding="unicode")})
    return snap


def sanitize_fragment(markup):
    """Parse an HTML fragment and remove scripts, event handlers and javascript: links."""
    try:
        frag = lhtml.fragments_fromstring(markup or "")
    except (etree.ParserError, ValueError):
        raise ToolError("The HTML could not be read.")
    out = []
    for f in frag:
        if isinstance(f, str):
            if f.strip():
                p = etree.Element("p")
                p.text = f
                out.append(p)
            continue
        for bad in f.xpath(".//script | .//iframe[not(contains(@src, 'youtube')) and not(contains(@src, 'vimeo'))] | "
                           ".//object | .//embed | .//form | .//base | .//meta | .//link"):
            bad.getparent().remove(bad)
        if f.tag in ("script", "object", "embed", "form", "base", "meta", "link"):
            continue
        for el in f.iter():
            if not isinstance(el.tag, str):
                continue
            for attr in list(el.attrib):
                if attr.lower().startswith("on") or attr.lower().startswith("t-"):
                    del el.attrib[attr]
                elif attr.lower() in ("href", "src") and el.attrib[attr].strip().lower().startswith("javascript:"):
                    el.attrib[attr] = "#"
        out.append(etree.fromstring(lhtml.tostring(f, method="xml", encoding="unicode"),
                                    parser=etree.XMLParser(recover=True)))
    return out
