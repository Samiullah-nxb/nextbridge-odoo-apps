from odoo.tests.common import TransactionCase
from odoo.exceptions import UserError

class TestAIFoundation(TransactionCase):

    def setUp(self):
        super().setUp()
        self.contract = self.env['clm.contract'].create({
            'name': 'Test Contract AI',
            'contract_type_id': self.env.ref('clm.contract_type_nda').id,
        })
        self.version = self.env['clm.contract.version'].create({
            'contract_id': self.contract.id,
            'version_type': 'internal_draft',
            'version_number': 1
        })
        # Add a clause to test deviations
        self.clause = self.env['clm.clause'].create({
            'name': 'Liability Cap',
            'standard_wording': 'Liability is capped at 1M.',
            'category': 'limitation_of_liability',
            'state': 'published'
        })

    def test_mock_ai_job_execution(self):
        # Create AI Job
        job = self.env['clm.ai.job'].create({
            'contract_version_id': self.version.id,
            'analysis_type': 'full',
            'provider': 'mock'
        })
        
        # Run Mock Engine
        job.action_run_sync()
        
        self.assertEqual(job.status, 'completed')
        
        # Verify Field Suggestions generated by Mock
        self.assertTrue(len(job.suggestion_ids) > 0)
        name_suggestion = job.suggestion_ids.filtered(lambda s: s.field_name == 'name')
        self.assertTrue(name_suggestion)
        
        # Verify Clause Deviations generated by Mock
        self.assertTrue(len(job.deviation_ids) > 0)

    def test_suggestion_review_workflow(self):
        job = self.env['clm.ai.job'].create({
            'contract_version_id': self.version.id,
            'analysis_type': 'field_extraction',
            'provider': 'mock'
        })
        job.action_run_sync()
        
        suggestion = job.suggestion_ids[0]
        self.assertEqual(suggestion.status, 'pending')
        
        original_name = self.contract.name
        
        # Reject should not modify contract
        suggestion.action_reject()
        self.assertEqual(suggestion.status, 'rejected')
        self.assertEqual(self.contract.name, original_name)
        
        # Approve should modify contract
        suggestion2 = job.suggestion_ids.filtered(lambda s: s.field_name == 'name')
        if suggestion2.status != 'pending':
            suggestion2.write({'status': 'pending'})
        suggestion2.action_approve()
        self.assertEqual(suggestion2.status, 'approved')
        self.assertEqual(self.contract.name, suggestion2.suggested_value)

    def test_deviation_review_workflow(self):
        job = self.env['clm.ai.job'].create({
            'contract_version_id': self.version.id,
            'analysis_type': 'clause_analysis',
            'provider': 'mock'
        })
        job.action_run_sync()
        
        deviation = job.deviation_ids[0]
        self.assertEqual(deviation.status, 'pending')
        
        # Legal changes the classification
        deviation.confirmed_deviation_type = 'approved_alternative'
        deviation.confirmed_risk_level = 'low'
        
        deviation.action_confirm()
        
        self.assertEqual(deviation.status, 'confirmed')
        self.assertEqual(deviation.confirmed_deviation_type, 'approved_alternative')
        self.assertEqual(deviation.confirmed_risk_level, 'low')
        # Ensure AI recommendation is preserved
        self.assertTrue(deviation.ai_deviation_type)
        self.assertNotEqual(deviation.ai_deviation_type, deviation.confirmed_deviation_type)

    def test_field_suggestion_sequence_and_fields(self):
        job = self.env['clm.ai.job'].create({
            'contract_version_id': self.version.id,
            'analysis_type': 'field_extraction',
            'provider': 'mock'
        })
        suggestion = self.env['clm.ai.field.suggestion'].create({
            'job_id': job.id,
            'field_name': 'effective_date',
            'suggested_value': '2026-09-01',
            'description': 'Effective date extracted from section 1',
            'context_reasoning': 'The clause states the agreement commences on Sept 1, 2026.',
        })
        self.assertTrue(suggestion.name.startswith('FS-'))
        self.assertEqual(len(suggestion.name), 8)
        self.assertEqual(suggestion.description, 'Effective date extracted from section 1')
        self.assertEqual(suggestion.context_reasoning, 'The clause states the agreement commences on Sept 1, 2026.')

        wizard = self.env['clm.ai.mapping.wizard'].create({
            'suggestion_id': suggestion.id,
        })
        self.assertIn("The AI extracted a value that doesn't match an existing", wizard.instruction_text)
        self.assertIn("Effective Date", wizard.instruction_text)

    def test_views_structure(self):
        # 1. clm.ai.field.suggestion form view
        suggestion_view = self.env['clm.ai.field.suggestion'].get_view(
            view_id=self.env.ref('clm_ai.view_clm_ai_field_suggestion_form').id,
            view_type='form'
        )
        arch = suggestion_view['arch']
        self.assertIn('name="name"', arch)
        self.assertIn('name="description"', arch)
        self.assertIn('name="context_reasoning"', arch)
        self.assertIn('string="Mapping Details"', arch)
        # The form still carries an Odoo title block. Matched as a class token
        # rather than as the whole attribute, because the NextContract design
        # system adds `o_clm_page_header` alongside `oe_title`.
        self.assertRegex(arch, r'class="[^"]*\boe_title\b[^"]*"')

        # 2. clm.ai.mapping.wizard form view
        wizard_view = self.env['clm.ai.mapping.wizard'].get_view(
            view_id=self.env.ref('clm_ai.view_clm_ai_mapping_wizard_form').id,
            view_type='form'
        )
        wizard_arch = wizard_view['arch']
        self.assertIn('name="instruction_text"', wizard_arch)
        self.assertIn('string="Confirm &amp; Approve"', wizard_arch)


